 assert.match(svg,/Small sample: 16 rent responses/);assert.match(svg,/95% interval/);
 await download.saveAs('dist/uncertainty-evidence/rents.svg');
 // A saved figure retains new policy and caveats across reload and print.
 await page.reload();await page.locator('[data-testid=gap-uncertainty]').waitFor();
 assert.match(await page.locator('[data-testid=gap-uncertainty]').innerText(),/Small sample: 16/);
 await page.evaluate(()=>{window.print=()=>{window.printedText=document.querySelector('#protection-host').innerText;};});
